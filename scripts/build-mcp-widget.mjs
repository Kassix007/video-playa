import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "server/generated/horsee-widget.ts");
const result = await build({
  entryPoints: [resolve(root, "mcp-app/horsee-widget.ts")],
  bundle: true,
  format: "esm",
  minify: true,
  target: "es2022",
  write: false,
});

const script = result.outputFiles[0]?.text;
if (!script) throw new Error("HORSEE MCP App widget bundle was empty.");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/build-mcp-widget.mjs. Do not edit directly.\nexport const HORSEE_WIDGET_SCRIPT = ${JSON.stringify(script)};\n`,
  "utf8",
);
